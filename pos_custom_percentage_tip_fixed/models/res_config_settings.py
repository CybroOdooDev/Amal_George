from odoo import fields, models


class ResConfigSettings(models.TransientModel):
    """Extend res.config.settings to expose custom tip percentage."""
    _inherit = 'res.config.settings'

    pos_custom_tip_percentage = fields.Float(
        string="Custom Percentage",
        help="Enter the percentage for custom tips",
        related="pos_config_id.custom_tip_percentage",
        readonly=False,
    )

